// Course Catalog

const makeCourse = (
  code: string,
  name: string,
  nameEn: string,
  credits: number,
  semester: number,
  type: string,
  prerequisites: string[] = [],
  isMandatory = true
): Course => ({
  id: `crs_${code.toLowerCase()}`,
  code,
  name,
  nameEn,
  credits,
  semester,
  curriculumYear: 2024,
  prerequisites: prerequisites.map(
    (item) => `crs_${item.toLowerCase()}`
  ),
  isMandatory,
  category:
    type === 'ELECTIVE'
      ? 'Pilihan'
      : type === 'General' || type === 'Pre-requisite'
        ? 'Wajib Universitas'
        : 'Wajib Prodi',
  description: `Kurikulum Informatika 2024–2028. Tipe: ${type}.`,
});

